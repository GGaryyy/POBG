import base64
import re
import xml.etree.ElementTree as ET
import zlib

import pytest

from src.tools import pob_export as pe
from src.tools.pob_export import BadCode, PobBuild, PobGem, PobSkillGroup, build_xml, decode_code, encode_code

ICE_SHOT = PobGem("Ice Shot", "Metadata/Items/Gem/SkillGemIceShot", "IceShot")   # PoB's own key has "Gem"
PIERCE = PobGem("Pierce I", "Metadata/Items/Gems/SupportGemPierce", "PierceSupport", support=True)
HERALD = PobGem("Herald of Ice", "Metadata/Items/Gems/SkillGemHeraldOfIce", "HeraldOfIce")


def sample(**over) -> PobBuild:
    fields = dict(title="Deadeye (POBG)", class_name="Ranger", class_id=2, ascendancy_name="Deadeye",
                  ascendancy_id="Ranger1", tree_version="0_5", nodes=["50459", "46990", "12033"],
                  groups=[PobSkillGroup("Ice Shot", (ICE_SHOT, PIERCE)), PobSkillGroup("Herald of Ice", (HERALD,))],
                  main_group=2, notes="Generated by POBG.\nNo gear.")
    fields.update(over)
    return PobBuild(**fields)


def parsed(build: PobBuild) -> ET.Element:
    return ET.fromstring(decode_code(encode_code(build_xml(build))))


def test_round_trip_gives_back_the_xml():
    xml = build_xml(sample())
    assert decode_code(encode_code(xml)) == xml


def test_code_is_zlib_in_url_safe_base64():
    code = encode_code(build_xml(sample()))
    assert re.fullmatch(r"[A-Za-z0-9_\-=]+", code)
    assert code.startswith("eN")                                   # zlib header 78 DA, as PoB writes it
    raw = base64.b64decode(code.replace("-", "+").replace("_", "/"))   # how PoB reads it
    assert zlib.decompress(raw).decode("utf-8") == build_xml(sample())


def test_same_build_gives_the_same_code():
    assert encode_code(build_xml(sample())) == encode_code(build_xml(sample()))


def test_build_and_tree_sections():
    root = parsed(sample())
    assert root.tag == "PathOfBuilding2"
    assert [child.tag for child in root] == ["Build", "Tree", "Skills", "Notes"]
    build = root.find("Build").attrib
    assert build["className"] == "Ranger" and build["ascendClassName"] == "Deadeye"
    assert build["targetVersion"] == "0_1" and build["characterLevelAutoMode"] == "true"
    assert build["mainSocketGroup"] == "2"
    spec = root.find("Tree/Spec").attrib
    assert root.find("Tree").attrib["activeSpec"] == "1"
    assert spec["classInternalId"] == "2" and spec["ascendancyInternalId"] == "Ranger1"
    assert spec["treeVersion"] == "0_5" and spec["secondaryAscendClassId"] == "0"
    assert spec["nodes"] == "50459,46990,12033" and spec["masteryEffects"] == ""


def test_skill_groups_keep_gem_order_and_ids():
    groups = parsed(sample()).findall("Skills/SkillSet/Skill")
    assert [g.attrib["label"] for g in groups] == ["Ice Shot", "Herald of Ice"]
    gems = [g.attrib for g in groups[0]]
    assert [(g["nameSpec"], g["gemId"], g["variantId"]) for g in gems] == [
        ("Ice Shot", "Metadata/Items/Gem/SkillGemIceShot", "IceShot"),
        ("Pierce I", "Metadata/Items/Gems/SupportGemPierce", "PierceSupport")]
    assert [g["level"] for g in gems] == ["20", "1"]                            # supports have no level
    assert {(g["quality"], g["enabled"], g["count"]) for g in gems} == {("0", "true", "1")}
    assert all(g.attrib["enabled"] == "true" and g.attrib["mainActiveSkill"] == "1" for g in groups)


def test_no_ascendancy_writes_an_empty_internal_id():
    root = parsed(sample(ascendancy_name=None, ascendancy_id=None))
    assert root.find("Tree/Spec").attrib["ascendancyInternalId"] == ""
    assert root.find("Build").attrib["ascendClassName"] == "None"


def test_notes_and_empty_parts():
    root = parsed(sample(notes="", groups=[], nodes=[]))
    assert root.find("Notes") is None
    assert root.find("Skills/SkillSet").findall("Skill") == []
    assert root.find("Tree/Spec").attrib["nodes"] == ""
    assert parsed(sample()).find("Notes").text == "Generated by POBG.\nNo gear."


def test_chinese_and_markup_characters_survive():
    root = parsed(sample(title='銳眼 <"&"> 流派', notes="不含裝備 & <b>"))
    assert root.find("Tree/Spec").attrib["title"] == '銳眼 <"&"> 流派'
    assert root.find("Notes").text == "不含裝備 & <b>"


def test_decode_tolerates_whitespace_and_missing_padding():
    code = encode_code(build_xml(sample()))
    split = " \n".join(code[i:i + 50] for i in range(0, len(code), 50))
    assert decode_code(split) == build_xml(sample())
    assert decode_code(code.rstrip("=")) == build_xml(sample())


@pytest.mark.parametrize("text", ["", "   ", "not a code!", "eNq", base64.urlsafe_b64encode(b"plain text").decode(),
                                  base64.urlsafe_b64encode(zlib.compress(b"\xff\xfe")).decode()])
def test_decode_rejects_what_is_not_a_code(text):
    with pytest.raises(BadCode):
        decode_code(text)


def test_decode_rejects_a_code_cut_off_in_the_middle():
    code = encode_code(build_xml(sample()))
    with pytest.raises(BadCode, match="cut off"):
        decode_code(code[:len(code) // 2])


def test_decode_refuses_long_input_and_inflation_past_the_limit(monkeypatch):
    with pytest.raises(BadCode, match="too long"):
        decode_code("A" * (pe.MAX_CODE_LEN + 1))
    monkeypatch.setattr(pe, "MAX_XML_LEN", 1000)
    bomb = base64.urlsafe_b64encode(zlib.compress(b"<a/>" * 10_000)).decode()
    with pytest.raises(BadCode, match="size limit"):
        decode_code(bomb)


def test_attribute_overrides_hold_all_three_lists():
    root = parsed(sample(attributes={"dex": ["5", "6"]}))
    node = root.find("Tree/Spec/Overrides/AttributeOverride")
    assert node.attrib == {"strNodes": "", "dexNodes": "5,6", "intNodes": ""}   # PoB reads all three
    assert parsed(sample()).find("Tree/Spec/Overrides") is None
    assert parsed(sample(attributes={"dex": []})).find("Tree/Spec/Overrides") is None


@pytest.mark.parametrize("bad", ["Cold\x01Witch", "a\x0bb", "lone \ud800 surrogate", "x\ufffe"])
def test_text_xml_cannot_hold_is_dropped(bad):
    root = parsed(sample(title=bad, notes=bad, groups=[PobSkillGroup(bad, (PobGem(bad, "g", "v"),))]))
    clean = pe.xml_text(bad)
    assert root.find("Tree/Spec").attrib["title"] == clean and root.find("Notes").text == clean
    assert root.find("Skills/SkillSet/Skill").attrib["label"] == clean
    assert root.find("Skills/SkillSet/Skill/Gem").attrib["nameSpec"] == clean


REAL_ACTS = [{"level": 1, "quest_points": 0}, {"level": 12, "quest_points": 4}, {"level": 28, "quest_points": 8},
             {"level": 44, "quest_points": 12}, {"level": 51, "quest_points": 16}, {"level": 64, "quest_points": 22},
             {"level": 62, "quest_points": 24}]   # PoB 0.23.1's QuestRewards.lua


@pytest.mark.parametrize("points, level", [(0, 1), (4, 5), (11, 12), (18, 15), (30, 27), (60, 49), (99, 76),
                                           (123, 100), (500, 100)])
def test_pob_level_matches_pobs_estimate(points, level):
    # 18 -> 15 was seen in PoB 0.23.1; the others were checked against a transcription of PoB's Lua loop
    assert pe.pob_level(points, REAL_ACTS) == level


def test_the_level_goes_into_the_build_section():
    assert parsed(sample(level=15)).find("Build").attrib["level"] == "15"


def test_gem_level_and_level_mode_are_written():
    gem = PobGem("Ice Shot", "g", "v", level=5)
    root = parsed(sample(groups=[PobSkillGroup("Ice Shot", (gem, PIERCE))], level=15, auto_level=False))
    assert [g.attrib["level"] for g in root.findall("Skills/SkillSet/Skill/Gem")] == ["5", "1"]
    assert root.find("Build").attrib["characterLevelAutoMode"] == "false"
